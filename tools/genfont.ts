// ---------------------------------------------------------------- validate
const chars: string[] = [];
for (let c = 32; c <= 126; c++) {
  const ch = String.fromCharCode(c);
  const g = G[ch];
  if (!g) throw new Error(`missing glyph for ${c} '${ch === " " ? "space" : ch}'`);
  if (g.length !== ROWS) throw new Error(`glyph '${ch}' has ${g.length} rows, want ${ROWS}`);
  g.forEach((row, i) => {
    if (row.length !== COLS) throw new Error(`glyph '${ch}' row ${i} has width ${row.length}, want ${COLS}`);
    if (!/^[#.]+$/.test(row)) throw new Error(`glyph '${ch}' row ${i} has illegal chars: ${row}`);
    if (i === ROWS - 1 && row !== ".".repeat(COLS)) {
      throw new Error(`glyph '${ch}' row ${i} must be the blank gap row`);
    }
  });
  chars.push(ch);
}
for (const key of Object.keys(G)) {
  if (key.length !== 1 || key.charCodeAt(0) < 32 || key.charCodeAt(0) > 126) {
    throw new Error(`glyph key '${key}' outside printable ASCII`);
  }
}

// ---------------------------------------------------------------- generate
const toBytes = (g: string[]): string[] =>
  g.map((row) => {
    let b = 0;
    for (let col = 0; col < COLS; col++) if (row[col] === "#") b |= 0x80 >> col;
    return `0x${b.toString(16).toUpperCase().padStart(2, "0")}`;
  });

const tableLines = chars.map((ch, i) => {
  const label = ch === " " ? "' '" : `'${ch}'`;
  return `    [${toBytes(G[ch]).join(", ")}], // ${32 + i} ${label}`;
});

const rust = `//! 8x8 bitmap font (T114) — glyph table generated by \`tools/genfont.ts\`.
//! Edit the generator's glyph blocks and re-run \`bun tools/genfont.ts\`;
//! do not hand-edit this file.
//!
//! Each glyph is one 8x8 cell: one row per byte, **bit 7 = leftmost pixel**
//! of that row (bit 3 = column 4). The 5x7 character occupies rows 0..=6 and
//! bits 7..=3; column 7 and row 7 are always blank — that is the 1px gap
//! between drawn glyphs. Glyph pixels paint, unpainted pixels are
//! transparent (left untouched).

use crate::engine::gfx::{Framebuffer, H, W};

/// Glyph cell width in px (5 used columns + 1 gap).
pub const FONT_W: u32 = 8;
/// Glyph cell height in px (7 used rows + 1 gap).
pub const FONT_H: u32 = 8;

/// 5x7 glyphs for printable ASCII 32..=126, indexed \`ch as usize - 32\`.
pub const GLYPHS: [[u8; 8]; 95] = [
${tableLines.join("\n")}
];

const FIRST: u8 = 32;
const LAST: u8 = 126;

/// Row-major glyph for \`ch\`: 8 bytes, one row each, bit 7 = leftmost pixel.
/// Printable ASCII 32..=126 maps to \`GLYPHS\`; anything else (control chars,
/// non-ASCII) returns the glyph for \`?\`.
#[inline]
pub fn glyph(ch: char) -> [u8; 8] {
    let c = ch as u32;
    if c >= FIRST as u32 && c <= LAST as u32 {
        GLYPHS[c as usize - FIRST as usize]
    } else {
        GLYPHS['?' as usize - FIRST as usize]
    }
}

/// Same bounds rule \`Framebuffer::set\` enforces; keeps pixel loops panic-safe.
#[inline]
fn in_bounds(x: i32, y: i32) -> bool {
    x >= 0 && y >= 0 && (x as u32) < W && (y as u32) < H
}

/// Draw \`s\` with top-left at (x,y): 8px cells with a 1px gap column, glyph
/// pixels painted in \`fg\`, background transparent, clipped to the screen.
pub fn draw_text(fb: &mut Framebuffer, x: i32, y: i32, s: &str, fg: u8) {
    let mut cx = x;
    for ch in s.chars() {
        for (row, bits) in glyph(ch).iter().enumerate() {
            for col in 0..8u32 {
                if bits & (0x80 >> col) != 0 {
                    let px = cx + col as i32;
                    let py = y + row as i32;
                    if in_bounds(px, py) {
                        fb.set(px, py, fg);
                    }
                }
            }
        }
        cx += FONT_W as i32;
    }
}

/// \`s\` at (x,y) in \`fg\), over an offset copy at (x+1,y+1) in \`shadow\`.
pub fn draw_text_shadow(fb: &mut Framebuffer, x: i32, y: i32, s: &str, fg: u8, shadow: u8) {
    draw_text(fb, x + 1, y + 1, s, shadow);
    draw_text(fb, x, y, s, fg);
}

/// On-screen width of \`s\` in px: 8 per char (chars, not bytes).
#[inline]
pub fn text_width(s: &str) -> u32 {
    s.chars().count() as u32 * FONT_W
}
`;

