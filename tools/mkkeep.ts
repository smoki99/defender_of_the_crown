// T-ART: Amiga-style keep sprite generator. Draws 21x24 keep sprites
// (Saxon/Norman roof tint, 2 flag frames each) + fog-dimmed variants and
// emits src/engine/art.rs with the pixel rows as readable ASCII art.
// Re-run: bun tools/mkkeep.ts
// Preview: bun tools/mkkeep.ts --preview && bun tools/ppm2png.ts tools/keep-preview.ppm tools/keep-preview.png

const W = 21, H = 24;
const CH: Record<string, number> = { '.': 32, K: 0, S: 2, r: 10, B: 12, D: 16, d: 17, g: 18, G: 19, L: 21, Y: 22 };

function blank(): string[][] {
  return Array.from({ length: H }, () => Array(W).fill('.'));
}
function put(g: string[][], x: number, y: number, c: string) {
  if (x < 0 || x >= W || y < 0 || y >= H) throw new Error(`oob ${x},${y}`);
  g[y][x] = c;
}
function hspan(g: string[][], y: number, x0: number, x1: number, c: string) {
  for (let x = x0; x <= x1; x++) put(g, x, y, c);
}

// One tower: roof cone + body rows 9..22. cx = body centre, half-width 4.
function tower(g: string[][], cx: number, roof: string) {
  put(g, cx - 1, 2, 'Y'); put(g, cx - 1, 3, 'Y'); put(g, cx - 1, 4, 'Y'); // pole
  hspan(g, 5, cx - 1, cx + 1, 'K');
  put(g, cx - 2, 6, 'K'); put(g, cx - 1, 6, roof); put(g, cx, 6, roof); put(g, cx + 1, 6, roof); put(g, cx + 2, 6, 'K');
  for (let x = cx - 3; x <= cx + 3; x++) put(g, x, 7, x === cx ? 'r' : x === cx - 3 || x === cx + 3 ? 'K' : roof);
  for (let x = cx - 4; x <= cx + 4; x++) put(g, x, 8, x === cx ? 'r' : x === cx - 4 || x === cx + 4 ? 'K' : roof);
  for (let y = 9; y <= 22; y++) {
    put(g, cx - 4, y, 'K'); put(g, cx + 4, y, 'K');
    for (let x = cx - 3; x <= cx + 3; x++) {
      let c = (x + y) % 3 === 0 ? 'g' : 'G';
      if (y % 5 === 2) c = 'D'; // mortar course
      if (x === cx - 3) c = 'L'; // sunlit edge
      if (x === cx + 3) c = 'd'; // shade edge
      put(g, x, y, c);
    }
  }
  put(g, cx, 11, 'K'); put(g, cx, 12, 'K'); // arrow slits
  put(g, cx, 16, 'K'); put(g, cx, 17, 'K');
}

// Curtain wall between the towers: merlon row with sky gaps, cap band,
// dithered stone, arched oak gate.
function wall(g: string[][], x0: number, x1: number) {
  for (let x = x0; x <= x1; x++) if ((x - x0) % 2 === 0) put(g, x, 11, 'G');
  hspan(g, 12, x0, x1, 'K');
  for (let y = 13; y <= 22; y++) {
    for (let x = x0; x <= x1; x++) {
      let c = (x + y) % 4 === 0 ? 'g' : 'G';
      if (y % 5 === 3) c = 'D';
      put(g, x, y, c);
    }
    put(g, x0, y, 'L'); put(g, x1, y, 'd');
  }
  const cx = Math.floor((x0 + x1) / 2);
  put(g, cx, 18, 'K'); put(g, cx - 1, 18, 'K'); put(g, cx + 1, 18, 'K');
  for (let y = 19; y <= 22; y++) { put(g, cx - 1, y, 'K'); put(g, cx, y, 'B'); put(g, cx + 1, y, 'K'); }
}

function flag(g: string[][], cx: number, frame: number, roof: string) {
  if (frame === 0) { put(g, cx, 2, roof); put(g, cx + 1, 2, roof); put(g, cx, 3, roof); }
  else { put(g, cx, 3, roof); put(g, cx + 1, 3, roof); }
}

function build(roof: string, frame: number): string[][] {
  const g = blank();
  tower(g, 4, roof);
  tower(g, 16, roof);
  wall(g, 8, 12);
  hspan(g, 23, 1, 19, 'D'); // ground shadow
  flag(g, 4, frame, roof);
  flag(g, 16, frame, roof);
  return g;
}

// fog: stone flattens to cold dark grey, roof/wood dim, outline stays
const FOG: Record<string, string> = { G: 'd', g: 'D', L: 'd', d: 'D', D: 'D', r: 'D', S: 'D', B: 'D', Y: 'g' };
function fog(g: string[][]): string[][] {
  return g.map((row) => row.map((c) => FOG[c] ?? c));
}

function paintRoof(g: string[][], from: string, to: string) {
  for (let y = 0; y < H; y++) for (let x = 0; x < W; x++) if (g[y][x] === from) g[y][x] = to;
}

const out: string[] = [];
out.push(`// Generated by tools/mkkeep.ts - DO NOT EDIT BY HAND (re-run the tool).`);
out.push(`//! T-ART: hand-drafted pixel-art keep sprites for the campaign map.`);
out.push(`use crate::engine::sprite::Sprite;`);
out.push(``);

const SPRITES: [string, string[][]][] = [
  ["KEEP_SAXON_0", build('S', 0)],
  ["KEEP_SAXON_1", build('S', 1)],
  ["KEEP_NORMAN_0", (() => { const g = build('S', 0); paintRoof(g, 'S', 'r'); return g; })()],
  ["KEEP_NORMAN_1", (() => { const g = build('S', 1); paintRoof(g, 'S', 'r'); return g; })()],
  ["KEEP_NEUTRAL_0", (() => { const g = build('S', 0); paintRoof(g, 'S', 'd'); paintRoof(g, 'r', 'D'); return g; })()],
  ["KEEP_SAXON_FOG", fog(build('S', 0))],
  ["KEEP_NORMAN_FOG", fog(build('S', 0).map((r, y) => r.map((c, x) => y < 9 && c === 'S' ? 'r' : c)))],
];

for (const [name, g] of SPRITES) {
  for (const r of g) if (r.length !== W) throw new Error(`${name} row width`);
  out.push(`const ${name}_PX: [u8; ${W * H}] = [${g.flat().map((c) => { if (!(c in CH)) throw new Error(`bad char ${c} in ${name}`); return CH[c]; }).join(",")}];`);
  out.push(`pub const ${name}: Sprite = Sprite::sized(${W}, ${H}, &${name}_PX);`);
  out.push(``);
}

const art = SPRITES.map(([n, g]) => `/* ${n}\n${g.map((r) => r.join("")).join("\n")}\n*/`).join("\n");
await Bun.write("src/engine/art.rs", `// ASCII art source (edit design in tools/mkkeep.ts, re-run):\n${art}\n\n${out.join("\n")}\n`);

if (Bun.argv.includes("--preview")) {
  const pw = (SPRITES.length + 1) * (W * 4 + 10), ph = H * 4 + 20;
  const img = new Uint8Array(pw * ph * 3);
  const px = (x: number, y: number, rgb: [number, number, number]) => { if (x >= 0 && y >= 0 && x < pw && y < ph) { const i = (y * pw + x) * 3; img[i] = rgb[0]; img[i + 1] = rgb[1]; img[i + 2] = rgb[2]; } };
  for (let y = 0; y < ph; y++) for (let x = 0; x < pw; x++) px(x, y, [102, 136, 51]);
  const RGB: Record<number, [number, number, number]> = { 0: [0, 0, 0], 2: [51, 102, 153], 10: [119, 17, 26], 12: [51, 34, 17], 16: [34, 34, 34], 17: [85, 77, 68], 18: [136, 128, 111], 19: [170, 162, 136], 21: [238, 238, 221], 22: [187, 153, 51], 32: [0, 0, 0] };
  SPRITES.forEach(([, g], si) => {
    const ox = 10 + si * (W * 4 + 10);
    g.forEach((row, y) => row.forEach((c, x) => {
      if (c === '.') return;
      for (let dy = 0; dy < 4; dy++) for (let dx = 0; dx < 4; dx++) px(ox + x * 4 + dx, 10 + y * 4 + dy, RGB[CH[c]]);
    }));
  });
  const header = new TextEncoder().encode(`P6\n${pw} ${ph}\n255\n`);
  const ppm = new Uint8Array(header.length + img.length);
  ppm.set(header);
  ppm.set(img, header.length);
  await Bun.write("tools/keep-preview.ppm", ppm);
  console.log("preview ppm written");
}
console.log("art.rs written,", SPRITES.length, "sprites");
